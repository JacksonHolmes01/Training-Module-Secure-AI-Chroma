#!/usr/bin/env bash
# Creates the gateway's tokens, its token map, and a TLS certificate.
# Safe to run more than once: existing secrets are kept.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p secrets

gen() { openssl rand -base64 32 | tr -d '/+=\n' | cut -c1-40; }

# token name           role:tenant
TOKENS=(
  "admin               admin:all"
  "acme_writer         writer:acme"
  "acme_reader         reader:acme"
  "globex_reader       reader:globex"
)

for entry in "${TOKENS[@]}"; do
  name=$(echo "$entry" | awk '{print $1}')
  f="secrets/${name}_token.txt"
  if [[ -s "$f" ]]; then
    echo "  kept     $f"
  else
    gen > "$f"; chmod 600 "$f"
    echo "  created  $f"
  fi
done

# Token map read by the gateway (always rebuilt from the token files)
{
  echo "# Generated by bin/setup_secrets.sh. Do not commit."
  for entry in "${TOKENS[@]}"; do
    name=$(echo "$entry" | awk '{print $1}')
    role=$(echo "$entry" | awk '{print $2}')
    echo "\"Bearer $(cat "secrets/${name}_token.txt")\" \"${role}\";"
  done
} > secrets/tokens.map
chmod 644 secrets/tokens.map
echo "  wrote    secrets/tokens.map"

# Self-signed TLS certificate for https://localhost:8443
if [[ -s secrets/server.crt && -s secrets/server.key ]]; then
  echo "  kept     secrets/server.crt and server.key"
else
  openssl req -x509 -newkey rsa:2048 -nodes -days 365 \
    -subj "/CN=localhost" \
    -addext "subjectAltName=DNS:localhost,IP:127.0.0.1" \
    -keyout secrets/server.key -out secrets/server.crt 2>/dev/null
  # The gateway reads the key as root before dropping privileges
  chmod 644 secrets/server.crt
  chmod 644 secrets/server.key
  echo "  created  secrets/server.crt and server.key"
fi
echo "Secrets ready."
