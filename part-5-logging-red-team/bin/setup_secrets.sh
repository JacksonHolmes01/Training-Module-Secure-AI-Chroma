#!/usr/bin/env bash
# Creates every secret this lab needs. Safe to run more than once:
# existing secrets are kept, never overwritten.
set -euo pipefail
cd "$(dirname "$0")/.."

gen() { openssl rand -base64 32 | tr -d '/+=\n' | cut -c1-40; }
mkdir -p secrets

TENANT="lab"
[[ -f .env ]] && TENANT="$(grep -E '^APP_TENANT=' .env | cut -d= -f2- || true)"
TENANT="${TENANT:-lab}"

# token name   role
for entry in "admin admin" "writer writer" "reader reader"; do
  name=${entry%% *}
  f="secrets/${name}_token.txt"
  if [[ -s "$f" ]]; then echo "  kept     $f"
  else gen > "$f"; chmod 644 "$f"; echo "  created  $f"; fi
done

# Token map for chroma-gateway (always rebuilt from the token files)
{
  echo "# Generated by bin/setup_secrets.sh. Do not commit."
  echo "\"Bearer $(cat secrets/admin_token.txt)\" \"admin:all\";"
  echo "\"Bearer $(cat secrets/writer_token.txt)\" \"writer:${TENANT}\";"
  echo "\"Bearer $(cat secrets/reader_token.txt)\" \"reader:${TENANT}\";"
} > secrets/tokens.map
echo "  wrote    secrets/tokens.map (tenant: ${TENANT})"

if [[ ! -f .env ]]; then
  cp .env.example .env
  echo "  created  .env (from .env.example)"
fi
if ! grep -qE '^EDGE_API_KEY=.{32,}' .env; then
  key="$(gen)"
  sed -i.bak "s|^EDGE_API_KEY=.*|EDGE_API_KEY=${key}|" .env && rm -f .env.bak
  echo "  created  EDGE_API_KEY in .env"
else
  echo "  kept     EDGE_API_KEY in .env"
fi
chmod 600 .env

# ---------------------------------------------------------------
# Edge API key as files, for the containers (Lesson 8)
# ---------------------------------------------------------------
KEY="$(grep -E '^EDGE_API_KEY=' .env | cut -d= -f2-)"
printf '%s' "$KEY" > secrets/edge_api_key.txt
printf '"%s" 1;\n' "$KEY" > secrets/edge_key.map
chmod 644 secrets/edge_api_key.txt secrets/edge_key.map secrets/tokens.map
echo "  wrote    secrets/edge_api_key.txt and secrets/edge_key.map"

# ---------------------------------------------------------------
# A private certificate authority (CA) and a certificate for the internal
# Chroma gateway, for encrypted, verified API-to-gateway traffic (Lesson 9).
# ---------------------------------------------------------------
if [[ -s secrets/tls_ca.crt && -s secrets/gateway.crt ]]; then
  echo "  kept     TLS certificates"
else
  openssl req -x509 -newkey rsa:2048 -nodes -days 365 -subj "/CN=Secure AI Lab CA" \
    -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" \
    -keyout secrets/tls_ca.key -out secrets/tls_ca.crt 2>/dev/null
  openssl req -newkey rsa:2048 -nodes -subj "/CN=chroma-gateway" \
    -keyout secrets/gateway.key -out secrets/gateway.csr 2>/dev/null
  printf 'subjectAltName=DNS:chroma-gateway\nextendedKeyUsage=serverAuth\n' > secrets/gateway.ext
  openssl x509 -req -in secrets/gateway.csr -CA secrets/tls_ca.crt -CAkey secrets/tls_ca.key \
    -CAcreateserial -days 365 -extfile secrets/gateway.ext -out secrets/gateway.crt 2>/dev/null
  rm -f secrets/gateway.csr secrets/gateway.ext secrets/tls_ca.srl
  chmod 600 secrets/tls_ca.key
  chmod 644 secrets/tls_ca.crt secrets/gateway.crt secrets/gateway.key
  echo "  created  TLS certificate authority and gateway certificate"
fi

# Part 4 reuses Part 2's downloaded models
docker volume create secure-ai-chroma-part2_ollama_data >/dev/null
echo "  ready    model volume secure-ai-chroma-part2_ollama_data"
echo "Secrets ready."
