#!/usr/bin/env bash
# Creates every secret this lab needs. Safe to run more than once:
# existing secrets are kept, never overwritten.
set -euo pipefail
cd "$(dirname "$0")/.."

gen() { openssl rand -base64 32 | tr -d '/+=\n' | cut -c1-40; }
mkdir -p secrets

TENANT="lab"
[[ -f .env ]] && TENANT="$(grep -E '^APP_TENANT=' .env | cut -d= -f2- || true)"
TENANT="${TENANT:-lab}"

# token name   role
for entry in "admin admin" "writer writer" "reader reader"; do
  name=${entry%% *}
  f="secrets/${name}_token.txt"
  if [[ -s "$f" ]]; then echo "  kept     $f"
  else gen > "$f"; chmod 644 "$f"; echo "  created  $f"; fi
done

# Token map for chroma-gateway (always rebuilt from the token files)
{
  echo "# Generated by bin/setup_secrets.sh. Do not commit."
  echo "\"Bearer $(cat secrets/admin_token.txt)\" \"admin:all\";"
  echo "\"Bearer $(cat secrets/writer_token.txt)\" \"writer:${TENANT}\";"
  echo "\"Bearer $(cat secrets/reader_token.txt)\" \"reader:${TENANT}\";"
} > secrets/tokens.map
echo "  wrote    secrets/tokens.map (tenant: ${TENANT})"

if [[ ! -f .env ]]; then
  cp .env.example .env
  echo "  created  .env (from .env.example)"
fi
if ! grep -qE '^EDGE_API_KEY=.{32,}' .env; then
  key="$(gen)"
  sed -i.bak "s|^EDGE_API_KEY=.*|EDGE_API_KEY=${key}|" .env && rm -f .env.bak
  echo "  created  EDGE_API_KEY in .env"
else
  echo "  kept     EDGE_API_KEY in .env"
fi
chmod 600 .env
echo "Secrets ready."
